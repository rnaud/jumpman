    /// One `geo_camera_fov` evaluation; returns the vertical FOV in degrees to render with.
    pub fn step_fov(&mut self) -> f64 {
        let f = &mut self.fov;
        match f.fov_func {
            CAM_FOV_SET_45 => f.fov = 45.0,
            CAM_FOV_SET_29 => f.fov = 29.0,
            CAM_FOV_ZOOM_30 => { let t = (30.0 - f.fov) / 60.0; approach_f32_symmetric_bool(&mut f.fov, 30.0, t); }
            CAM_FOV_DEFAULT => {
                self.status_flags &= !CAM_FLAG_SLEEPING;
                if self.mario.action == act::SLEEPING || self.mario.action == act::START_SLEEPING {
                    let t = (30.0 - f.fov) / 30.0;
                    approach_f32_symmetric_bool(&mut f.fov, 30.0, t);
                    self.status_flags |= CAM_FLAG_SLEEPING;
                } else {
                    let t = (45.0 - f.fov) / 30.0;
                    approach_f32_symmetric_bool(&mut f.fov, 45.0, t);
                }
            }
            CAM_FOV_BBH => {
                let target = if self.c.mode == CAMERA_MODE_FIXED && self.c.cutscene == 0 { 60.0 } else { 45.0 };
                f.fov = approach_f32(f.fov, target, 2.0, 2.0);
            }
            CAM_FOV_APP_45 => f.fov = approach_f32(f.fov, 45.0, 2.0, 2.0),
            CAM_FOV_SET_30 => f.fov = 30.0,
            CAM_FOV_APP_20 => { approach_f32_symmetric_bool(&mut f.fov, 20.0, 0.3); }
            CAM_FOV_APP_80 => { approach_f32_symmetric_bool(&mut f.fov, 80.0, 3.5); }
            CAM_FOV_APP_30 => { approach_f32_symmetric_bool(&mut f.fov, 30.0, 1.0); }
            CAM_FOV_APP_60 => { approach_f32_symmetric_bool(&mut f.fov, 60.0, 1.0); }
            _ => {}
        }
        // shake_camera_fov
        let mut out = f.fov;
        if f.shake_amplitude != 0.0 {
            f.fov_offset = crate::math::coss(f.shake_phase as f64) * f.shake_amplitude / 256.0;
            f.shake_phase = w(f.shake_phase + f.shake_speed);
            let d = f.decay as f64;
            approach_f32_symmetric_bool(&mut f.shake_amplitude, 0.0, d);
            out += f.fov_offset;
        } else {
            f.shake_phase = 0;
        }
        out
    }

