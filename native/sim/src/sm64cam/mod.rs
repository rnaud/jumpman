    /// `set_camera_mode`
    pub fn set_camera_mode(&mut self, e: &Env, mut mode: i32, frames: i32) {
        if mode == CAMERA_MODE_WATER_SURFACE && self.curr_level_area == AREA_TTM_OUTSIDE {
            return;
        }
        self.movement_flags &= !(CAM_MOVE_RESTRICT | CAM_MOVE_ROTATE);
        self.movement_flags |= CAM_MOVING_INTO_MODE;
        if mode == CAMERA_MODE_NONE {
            mode = CAMERA_MODE_CLOSE;
        }
        self.c_up_camera_pitch = 0;
        self.mode_offset_yaw = 0;
        self.lakitu_dist = 0;
        self.lakitu_pitch = 0;
        self.area_yaw_change = 0;
        self.mode_info.new_mode = if mode != -1 { mode } else { self.mode_info.last_mode };
        self.mode_info.last_mode = self.c.mode;
        self.mode_info.max = frames;
        self.mode_info.frame = 1;
        self.c.mode = self.mode_info.new_mode;
        self.lakitu.mode = self.c.mode;
        let mp = self.mario.pos;
        let mut end_focus = self.c.focus;
        sub(&mut end_focus, mp);
        let mut end_pos = self.c.pos;
        sub(&mut end_pos, mp);
        // sModeTransitions[newMode](c, end->focus, end->pos): the update function with the
        // end points as its output arguments (they were already shifted by Mario's position).
        let (yaw, f, p) = self.mode_transition_fn(e, self.mode_info.new_mode, end_focus, end_pos);
        self.area_yaw = yaw;
        end_focus = f;
        end_pos = p;
        sub(&mut end_focus, mp);
        sub(&mut end_pos, mp);
        let mut start_focus = self.lakitu.cur_focus;
        sub(&mut start_focus, mp);
        let mut start_pos = self.lakitu.cur_pos;
        sub(&mut start_pos, mp);
        let (sd, sp, sy) = dist_and_angle(start_focus, start_pos);
        let (ed, ep, ey) = dist_and_angle(end_focus, end_pos);
        self.mode_info.start = LinearPoint { focus: start_focus, pos: start_pos, dist: sd, pitch: sp, yaw: sy };
        self.mode_info.end = LinearPoint { focus: end_focus, pos: end_pos, dist: ed, pitch: ep, yaw: ey };
    }

