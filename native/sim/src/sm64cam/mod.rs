//! Port of the SM64 camera (`src/game/camera.c`, US): Lakitu follow, the CAMERA_MODE_* update
//! functions, surface / area camera triggers, mode transitions, shakes, FOV and the gameplay
//! CUTSCENE_* sequences. Engine-free: it is fed a [`Env`] snapshot of Mario, the controller and
//! the collision world each 30 Hz tick and leaves the result in [`SmCam::lakitu`] (`pos`,
//! `focus`, `roll`) and [`SmCam::fov`].
//!
//! Arithmetic is f64 (the decomp is f32) and the s16 conversions are explicit, so the logic is
//! verbatim but outputs are not bit-identical to the ROM.
//!
//! Layout: `util` (math_util / camera.c helpers), `modes` (the mode_* update functions),
//! `triggers` (surface + per-level area triggers, `camera_course_processing`), `cutscenes`
//! (CUTSCENE_* shots), `data` (generated by `scripts/export-sm64-camera.py`).
