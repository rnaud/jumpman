    fn increment_shake_offset(offset: &mut i32, inc: i32) {
        if inc == -0x8000 {
            *offset = (*offset & 0x8000) + 0xC000;
        } else {
            *offset += inc;
        }
        *offset = w(*offset);
    }

    /// `shake_camera_pitch`
    pub fn shake_camera_pitch(&mut self, pos: V3, focus: &mut V3) {
        let l = &mut self.lakitu;
        if l.shake_magnitude[0] | l.shake_magnitude[1] != 0 {
            let (dist, mut pitch, yaw) = dist_and_angle(pos, *focus);
            pitch = w(pitch + s16(l.shake_magnitude[0] as f64 * crate::math::sins(l.shake_pitch_phase as f64)));
            *focus = set_dist_and_angle(pos, dist, pitch, yaw);
            Self::increment_shake_offset(&mut l.shake_pitch_phase, l.shake_pitch_vel);
            if !approach_s16_symmetric_bool(&mut l.shake_magnitude[0], 0, l.shake_pitch_decay) {
                l.shake_pitch_phase = 0;
            }
        }
    }
    /// `shake_camera_yaw`
    pub fn shake_camera_yaw(&mut self, pos: V3, focus: &mut V3) {
        let l = &mut self.lakitu;
        if l.shake_magnitude[1] != 0 {
            let (dist, pitch, mut yaw) = dist_and_angle(pos, *focus);
            yaw = w(yaw + s16(l.shake_magnitude[1] as f64 * crate::math::sins(l.shake_yaw_phase as f64)));
            *focus = set_dist_and_angle(pos, dist, pitch, yaw);
            Self::increment_shake_offset(&mut l.shake_yaw_phase, l.shake_yaw_vel);
            if !approach_s16_symmetric_bool(&mut l.shake_magnitude[1], 0, l.shake_yaw_decay) {
                l.shake_yaw_phase = 0;
            }
        }
    }
    /// `shake_camera_roll`
    pub fn shake_camera_roll(&mut self, roll: &mut i32) {
        let l = &mut self.lakitu;
        if l.shake_magnitude[2] != 0 {
            Self::increment_shake_offset(&mut l.shake_roll_phase, l.shake_roll_vel);
            *roll += s16(l.shake_magnitude[2] as f64 * crate::math::sins(l.shake_roll_phase as f64));
            if !approach_s16_symmetric_bool(&mut l.shake_magnitude[2], 0, l.shake_roll_decay) {
                l.shake_roll_phase = 0;
            }
        }
    }

