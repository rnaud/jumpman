/// `find_c_buttons_pressed`
pub fn find_c_buttons_pressed(mut cur: u16, pressed: u16, down: u16) -> u16 {
    let pressed = pressed & CBUTTON_MASK;
    let down = down & CBUTTON_MASK;
    if pressed & L_CBUTTONS != 0 {
        cur |= L_CBUTTONS;
        cur &= !R_CBUTTONS;
    }
    if down & L_CBUTTONS == 0 {
        cur &= !L_CBUTTONS;
    }
    if pressed & R_CBUTTONS != 0 {
        cur |= R_CBUTTONS;
        cur &= !L_CBUTTONS;
    }
    if down & R_CBUTTONS == 0 {
        cur &= !R_CBUTTONS;
    }
    if pressed & U_CBUTTONS != 0 {
        cur |= U_CBUTTONS;
        cur &= !D_CBUTTONS;
    }
    if down & U_CBUTTONS == 0 {
        cur &= !U_CBUTTONS;
    }
    if pressed & D_CBUTTONS != 0 {
        cur |= D_CBUTTONS;
        cur &= !U_CBUTTONS;
    }
    if down & D_CBUTTONS == 0 {
        cur &= !D_CBUTTONS;
    }
    cur
}

