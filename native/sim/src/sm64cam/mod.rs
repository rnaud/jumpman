    /// `reduce_by_dist_from_camera`
    pub fn reduce_by_dist_from_camera(&self, value: i32, mut max_dist: f64, p: V3) -> i32 {
        let g = self.lakitu.goal_pos;
        let (dx, dy, dz) = (g[0] - p[0], g[1] - p[1], g[2] - p[2]);
        let mut dist = (dx * dx + dy * dy + dz * dz).sqrt();
        let mut result = 0;
        if max_dist > dist {
            let (d, mut pitch, mut yaw) = dist_and_angle(g, p);
            dist = d;
            if dist < max_dist {
                let (gp, gy) = calculate_angles(g, self.lakitu.goal_focus);
                pitch = w(pitch - gp);
                yaw = w(yaw - gy);
                dist -= 2000.0;
                if dist < 0.0 { dist = 0.0; }
                max_dist -= 2000.0;
                if max_dist < 2000.0 { max_dist = 2000.0; }
                result = s16(value as f64 * (1.0 - dist / max_dist));
                if pitch < -0x1800 || pitch > 0x400 || yaw < -0x1800 || yaw > 0x1800 {
                    result /= 2;
                }
            }
        }
        result
    }
    pub fn set_pitch_shake_from_point(&mut self, mag: i32, decay: i32, inc: i32, max_dist: f64, p: V3) {
        let mag = self.reduce_by_dist_from_camera(mag, max_dist, p);
        if mag != 0 { self.set_camera_pitch_shake(mag, decay, inc); }
    }
    pub fn set_fov_shake_from_point(&mut self, amp: i32, decay: i32, speed: i32, max_dist: f64, p: V3) {
        let amp = self.reduce_by_dist_from_camera(amp, max_dist, p);
        if amp != 0 { self.set_fov_shake(amp, decay, speed); }
    }

    /// `set_camera_shake_from_hit`
    pub fn set_camera_shake_from_hit(&mut self, shake: i32) {
        let water = self.mario.action & (act::FLAG_SWIMMING | act::FLAG_METAL_WATER) != 0;
        match shake {
            SHAKE_ATTACK => { self.lakitu.foc_h_speed = 0.0; self.lakitu.pos_h_speed = 0.0; }
            SHAKE_FALL_DAMAGE => { self.set_camera_pitch_shake(0x60, 0x3, 0x8000); self.set_camera_roll_shake(0x60, 0x3, 0x8000); }
            SHAKE_GROUND_POUND => self.set_camera_pitch_shake(0x60, 0xC, 0x8000),
            SHAKE_SMALL_DAMAGE | SHAKE_MED_DAMAGE | SHAKE_LARGE_DAMAGE => {
                let (yaw, roll, fov, yd, rd) = match (shake, water) {
                    (SHAKE_SMALL_DAMAGE, true) => ((0x200, 0x10, 0x1000), (0x400, 0x20, 0x1000), (0x100, 0x30), 0, 0),
                    (SHAKE_SMALL_DAMAGE, false) => ((0x80, 0x8, 0x4000), (0x80, 0x8, 0x4000), (0x100, 0x30), 0, 0),
                    (SHAKE_MED_DAMAGE, true) => ((0x400, 0x20, 0x1000), (0x600, 0x30, 0x1000), (0x180, 0x40), 0, 0),
                    (SHAKE_MED_DAMAGE, false) => ((0x100, 0x10, 0x4000), (0x100, 0x10, 0x4000), (0x180, 0x40), 0, 0),
                    (_, true) => ((0x600, 0x30, 0x1000), (0x800, 0x40, 0x1000), (0x200, 0x50), 0, 0),
                    (_, false) => ((0x180, 0x20, 0x4000), (0x200, 0x20, 0x4000), (0x200, 0x50), 0, 0),
                };
                let _ = (yd, rd);
                self.set_camera_yaw_shake(yaw.0, yaw.1, yaw.2);
                self.set_camera_roll_shake(roll.0, roll.1, roll.2);
                self.set_fov_shake(fov.0, fov.1, 0x8000);
                self.lakitu.foc_h_speed = 0.0;
                self.lakitu.pos_h_speed = 0.0;
            }
            SHAKE_HIT_FROM_BELOW => { self.lakitu.foc_h_speed = 0.07; self.lakitu.pos_h_speed = 0.07; }
            SHAKE_SHOCK => {
                self.set_camera_pitch_shake((crate::math::random() * 64.0) as i32, 0x8, 0x8000);
                self.set_camera_yaw_shake((crate::math::random() * 64.0) as i32, 0x8, 0x8000);
            }
            _ => {}
        }
    }

