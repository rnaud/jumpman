    /// `f32_find_wall_collision`: push `pos` out of walls; returns the number of walls hit.
    pub fn wall_push(&self, e: &Env, pos: &mut V3, offset_y: f64, radius: f64) -> usize {
        let mut d = crate::collision::WallData { x: pos[0], y: pos[1], z: pos[2], offset_y, radius, walls: vec![] };
        let n = e.world.find_wall_collisions(&mut d, true);
        *pos = [d.x, d.y, d.z];
        n
    }
    /// `collide_with_walls`
    pub fn collide_with_walls(&self, e: &Env, pos: &mut V3, offset_y: f64, radius: f64) -> usize {
        let mut d = crate::collision::WallData { x: pos[0], y: pos[1], z: pos[2], offset_y, radius, walls: vec![] };
        let n = e.world.find_wall_collisions(&mut d, true);
        if n != 0 {
            for _ in 0..d.walls.len() {
                let wall = d.walls.last().unwrap();
                let [nx, ny, nz] = wall.normal;
                let offset = nx * pos[0] + ny * pos[1] + nz * pos[2] + wall.origin_offset;
                if offset.abs() < radius {
                    pos[0] += nx * (radius - offset);
                    pos[2] += nz * (radius - offset);
                }
            }
        }
        n
    }

