        self.dir8_base_yaw = 0;
        self.dir8_yaw_offset = 0;
        self.c.door_status = DOOR_DEFAULT;
        self.head_rotation = [0; 2];
        self.camera_event = 0;
        self.lakitu.shake_magnitude = [0; 3];
        self.lakitu.last_frame_action = 0;
        self.set_fov_function(CAM_FOV_DEFAULT);
