    /// `shake_camera_handheld`
    pub fn shake_camera_handheld(&mut self, pos: V3, focus: &mut V3) {
        let h = &mut self.handheld;
        let offset = if h.mag == 0 {
            [0.0; 3]
        } else {
            let o = evaluate_cubic_spline(h.timer, h.spline[0], h.spline[1], h.spline[2], h.spline[3]);
            h.timer += h.inc;
            if 1.0 <= h.timer {
                for i in 0..3 { h.spline[i] = h.spline[i + 1]; }
                let r = |range: f64| -> f64 { (crate::math::random() * range - range / 2.0).trunc() };
                let m = h.mag as f64;
                h.spline[3] = [r(m), r(m), r(m / 2.0)];
                h.timer -= 1.0;
                h.inc = crate::math::random() * 0.5;
                if h.inc < 0.02 { h.inc = 0.02; }
            }
            o
        };
        approach_s16_asymptotic_bool(&mut h.pitch, s16(offset[0]), 0x08);
        approach_s16_asymptotic_bool(&mut h.yaw, s16(offset[1]), 0x08);
        approach_s16_asymptotic_bool(&mut h.roll, s16(offset[2]), 0x08);
        if h.pitch | h.yaw != 0 {
            let (dist, pitch, yaw) = dist_and_angle(pos, *focus);
            *focus = set_dist_and_angle(pos, dist, w(pitch + h.pitch), w(yaw + h.yaw));
        }
        h.mag = 0;
        h.inc = 0.0;
    }

