    pub fn set_cam_angle(&mut self, mode: i32) -> i32 {
        let mut cur = CAM_ANGLE_LAKITU;
        if mode == CAM_ANGLE_MARIO && self.selection_flags & CAM_MODE_MARIO_ACTIVE == 0 {
            self.selection_flags |= CAM_MODE_MARIO_ACTIVE;
            if self.movement_flags & CAM_MOVE_ZOOMED_OUT != 0 {
                self.selection_flags |= CAM_MODE_LAKITU_WAS_ZOOMED_OUT;
                self.movement_flags &= !CAM_MOVE_ZOOMED_OUT;
            }
        }
        if mode == CAM_ANGLE_LAKITU && self.selection_flags & CAM_MODE_MARIO_ACTIVE != 0 {
            self.selection_flags &= !CAM_MODE_MARIO_ACTIVE;
            if self.selection_flags & CAM_MODE_LAKITU_WAS_ZOOMED_OUT != 0 {
                self.selection_flags &= !CAM_MODE_LAKITU_WAS_ZOOMED_OUT;
                self.movement_flags |= CAM_MOVE_ZOOMED_OUT;
            } else {
                self.movement_flags &= !CAM_MOVE_ZOOMED_OUT;
            }
        }
        if self.selection_flags & CAM_MODE_MARIO_ACTIVE != 0 {
            cur = CAM_ANGLE_MARIO;
        }
        cur
    }

