import * as THREE from 'three';
import { expect, it } from 'vitest';
import { CoinEffects } from '../src/game/coinEffects';

it('bounces the orange number for 36 ticks and spawns three staggered coin sparkles', () => {
  const root = new THREE.Group();
  const effects = new CoinEffects(root,path => Object.assign(new THREE.Group(),{name:path}));
  effects.number(3,new THREE.Vector3(10,100,-30));
  const digit = root.children[0];
  expect(digit.name).toContain('geo_switch_anim_state_3');
  expect(digit.position.toArray()).toEqual([10,125,-30]);
  for (let i=0;i<13;i++) effects.step();
  expect(digit.position.y).toBe(307);
  for (let i=13;i<24;i++) effects.step();
  expect(digit.position.y).toBe(197);
  effects.step();
  expect(digit.position.y).toBe(211);
  for (let i=25;i<36;i++) effects.step();
  expect(digit.parent).toBeNull();
  expect(root.children).toHaveLength(1);
  expect(root.children[0].position.y).toBe(digit.position.y+25);
  effects.step(); effects.step();
  expect(root.children).toHaveLength(3);
  const camera = new THREE.PerspectiveCamera();
  camera.rotation.y = 1;
  effects.faceCamera(camera);
  expect(root.children.every(o=>o.quaternion.equals(camera.quaternion))).toBe(true);
  for(let i=0;i<11;i++) effects.step();
  expect(root.children).toHaveLength(0);
  effects.number(7,new THREE.Vector3());
  effects.clear();
  expect(root.children).toHaveLength(0);
});
