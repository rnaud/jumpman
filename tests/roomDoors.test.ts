import { readFileSync } from 'node:fs';
import * as THREE from 'three';
import { describe, expect, it } from 'vitest';
import { CollisionWorld } from '../src/sim/collision';
import { MarioRuntime } from '../src/sim/MarioRuntime';
import { ACT_IDLE, ACT_WALKING, ACT_UNLOCKING_STAR_DOOR } from '../src/sim/state';
import { RoomDoors, DoorCollider, type RoomDoor } from '../src/game/roomDoors';
import { SaveFile } from '../src/game/save';
import { addNativeCollision } from '../src/game/nativeCollision';

describe('castle room doors', () => {
  it('blocks the WF room until the first star, opens it, and carries Mario through using the source clip', () => {
    const data = JSON.parse(readFileSync('assets/courses/castle_inside.json', 'utf8'));
    const world = new CollisionWorld();
    addNativeCollision(world, data);
    const door: RoomDoor = data.roomDoors.find((d: RoomDoor) => d.stars === 1 && d.pos[1] === 0);
    const [x, y, z] = door.pos;
    const doors = new RoomDoors(data.doorMotion);
    const before = world.surfaces.length;
    doors.add({door, model: new THREE.Group(), collision: new DoorCollider(world, data.extraCollision.door, door.yaw)});
    expect(world.surfaces.length).toBe(before + 4);
    const save = new SaveFile();
    const m = new MarioRuntime(world, { pos: [x, y, z + 95], faceYaw: -32768 });
    m.setAction(ACT_WALKING);
    const hints: string[] = [];
    expect(doors.step(m, save, msg => hints.push(msg))).toBe(false);
    expect(hints).toHaveLength(1);
    save.collectStar('bob');
    expect(doors.step(m, save, () => {})).toBe(true);
    expect(m.action).toBe(ACT_UNLOCKING_STAR_DOOR);
    for (let tick = 0; tick < 161; tick++) doors.step(m, save, () => {});
    expect(save.hasFlag(1 << 11)).toBe(true);
    doors.step(m, save, () => {});
    expect(world.surfaces.length).toBe(before);
    for (let tick = 0; tick < 80; tick++) doors.step(m, save, () => {});
    expect(m.action).toBe(ACT_IDLE);
    expect(m.pos[2]).toBeLessThan(z - 200);
    expect(world.surfaces.length).toBe(before + 4);
  });
  it('separates and recloses both halves of the eight-star door', () => {
    const data = JSON.parse(readFileSync('assets/courses/castle_inside.json', 'utf8'));
    const world = new CollisionWorld();
    addNativeCollision(world, data);
    const doors = new RoomDoors(data.doorMotion);
    const leaves = (data.roomDoors as RoomDoor[]).filter(door => door.stars === 8).map(door => {
      const model = new THREE.Group();
      model.position.fromArray(door.pos);
      doors.add({ door, model, collision: new DoorCollider(world, data.extraCollision.star_door, door.yaw) });
      return { model, home: model.position.clone() };
    });
    expect(leaves).toHaveLength(2);
    const home = leaves[0].home;
    const mario = new MarioRuntime(world, {pos: [home.x + 50, home.y, home.z + 50], faceYaw: -24576});
    const save = new SaveFile();
    for (let i = 1; i <= 6; i++) save.collectStar('bob', i);
    save.collectStar('wf');
    save.collectStar('ccm');
    mario.setAction(ACT_WALKING);
    const step = () => doors.step(mario, save, () => {});
    step();
    for (let i = 0; i < 161; i++) step();
    step();
    for (let i = 0; i < 17; i++) step();
    for (const leaf of leaves) expect(leaf.home.distanceTo(leaf.model.position)).toBeCloseTo(136);
    for (let i = 17; i < 66; i++) step();
    expect(mario.action).toBe(ACT_IDLE);
    for (const leaf of leaves) expect(leaf.home.distanceTo(leaf.model.position)).toBeCloseTo(0);
  });
});
