"""Export the level-specific SM64 camera data from reference/sm64 into
native/sim/src/sm64cam/data.rs (checked in; regenerate after changing reference/sm64).

Exports, all parsed straight from the decomp:
  * LEVEL_* numbers (levels/level_defines.h order) and the level folder name for each,
  * the per-level `struct CameraTrigger` tables (sCamSL ... sCamBBH in src/game/camera.c)
    and the `sCameraTriggers[]` level -> table mapping,
  * the `GEO_CAMERA(mode, ..., focusX, focusY, focusZ)` of every area geo layout
    (default camera mode and the area centre used by the radial / boss cameras),
  * `sBBHLibraryParTrackPath`, `sFixedModeBasePosition`,
  * `sDanceCutsceneIndexTable` (levels/course_defines.h, DROT-rotated like camera.c does).
Usage: python3 scripts/export-sm64-camera.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / 'reference/sm64'
OUT = ROOT / 'native/sim/src/sm64cam/data.rs'


def strip(text):
    return re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)


def camel(name):
    return ''.join(p.capitalize() for p in name.split('_'))


def main():
    cam = strip((REF / 'src/game/camera.c').read_text())
    levels = []  # (const name, folder, table)
    level_courses = {}
    courses = {}
    for i, m in enumerate(re.finditer(r'DEFINE_(?:BONUS_)?COURSE\(\s*(\w+)\s*,', strip((REF / 'levels/course_defines.h').read_text()))):
        courses[m[1]] = i
    for m in re.finditer(r'^(STUB_LEVEL|DEFINE_LEVEL)\((.*)\)\s*$', strip((REF / 'levels/level_defines.h').read_text()), re.M):
        parts = [p.strip() for p in m[2].split(',')]
        if m[1] == 'STUB_LEVEL':
            levels.append((parts[1], '', parts[-1]))
        else:
            levels.append((parts[1], parts[3], parts[-1]))
        level_courses[parts[1]] = courses.get(parts[2], 0)

    tables = {}
    events = []
    for name, body in re.findall(r'struct CameraTrigger (sCam\w+)\[\]\s*=\s*\{(.*?)\n\};', cam, re.S):
        rows = []
        for r in re.findall(r'\{\s*(-?\d+)\s*,\s*(\w+)\s*,([^{}]*)\}', body):
            if r[1] == 'NULL':
                continue
            vals = [int(v, 0) for v in r[2].split(',') if v.strip()]
            assert len(vals) == 7, (name, r)
            ev = camel(r[1].removeprefix('cam_'))
            if ev not in events:
                events.append(ev)
            rows.append((int(r[0]), ev, vals))
        tables[name] = rows

    # Area cameras from the geo layouts.
    area_cams = []
    for lv, folder, _ in levels:
        if not folder:
            continue
        for geo in sorted((REF / 'levels' / folder / 'areas').glob('*/geo.inc.c')):
            area = int(geo.parent.name)
            m = re.search(r'GEO_CAMERA\(\s*(\d+)\s*,\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)', geo.read_text())
            if m:
                area_cams.append((lv, area, int(m[1]), int(m[5]), int(m[6]), int(m[7])))

    par = re.search(r'sBBHLibraryParTrackPath\[\]\s*=\s*\{(.*?)\};', cam, re.S)[1]
    par_rows = re.findall(r'\{\s*(-?\d+),\s*\{\s*(-?[\d.]+)f,\s*(-?[\d.]+)f,\s*(-?[\d.]+)f\s*\},\s*(-?[\d.]+)f,\s*(-?[\d.]+)f\s*\}', par)
    fixed = re.search(r'sFixedModeBasePosition\s*=\s*\{\s*(-?[\d.]+)f,\s*(-?[\d.]+)f,\s*(-?[\d.]+)f', cam)

    # Dance table: DEFINE_COURSE / DEFINE_BONUS_COURSE order + trailing literal row (camera.c).
    dance = []
    for m in re.finditer(r'DEFINE_(?:BONUS_)?COURSE\(\s*\w+\s*,\s*(0x[0-9A-Fa-f]+)\s*\)', strip((REF / 'levels/course_defines.h').read_text())):
        v = int(m[1], 16)
        row = []
        for i in range(4):
            b = (v >> (32 - (i + 1) * 8)) & 0xFF
            row.append(((b & 0xF0) >> 4) | ((b & 0x0F) << 4))
        dance.append(row)
    dance.append([0x44, 0x44, 0x44, 0x04])

    o = []
    o.append('//! @generated by scripts/export-sm64-camera.py from reference/sm64 (src/game/camera.c, levels/*).')
    o.append('//! Do not edit by hand; rerun the script.')
    o.append('#![allow(dead_code)]')
    o.append('')
    for i, (lv, folder, _) in enumerate(levels, start=1):
        o.append(f'pub const {lv}: i32 = {i};')
    o.append('')
    o.append('/// Level folder name (`levels/<name>`, the course ids of the native port) -> LEVEL_* number.')
    o.append('pub fn level_for_course(id: &str) -> Option<i32> {')
    o.append('    Some(match id {')
    for i, (lv, folder, _) in enumerate(levels, start=1):
        if folder:
            o.append(f'        "{folder}" => {lv},')
    o.append('        _ => return None,')
    o.append('    })')
    o.append('}')
    o.append('')
    o.append('/// `gCurrCourseNum` of a level (`COURSE_*` from levels/course_defines.h order; 0 = none).')
    o.append('pub fn course_for_level(level: i32) -> i32 {')
    o.append('    match level {')
    for lv, c in level_courses.items():
        if c:
            o.append(f'        {lv} => {c},')
    o.append('        _ => 0,')
    o.append('    }')
    o.append('}')
    o.append('')
    o.append('/// `cam_*` trigger callbacks of camera.c (the match lives in `sm64cam::triggers`).')
    o.append('#[derive(Clone, Copy, PartialEq, Eq, Debug)]')
    o.append('pub enum Ev {')
    for e in events:
        o.append(f'    {e},')
    o.append('}')
    o.append('')
    o.append('/// `struct CameraTrigger`: area, event, centre xyz, bounds xyz, bounds yaw.')
    o.append('#[derive(Clone, Copy, Debug)]')
    o.append('pub struct Trigger { pub area: i8, pub ev: Ev, pub center: [i16; 3], pub bounds: [i16; 3], pub yaw: i32 }')
    o.append('')
    for name, rows in tables.items():
        o.append(f'pub static {name.upper()}: [Trigger; {len(rows)}] = [')
        for area, ev, v in rows:
            o.append(f'    Trigger {{ area: {area}, ev: Ev::{ev}, center: [{v[0]}, {v[1]}, {v[2]}], bounds: [{v[3]}, {v[4]}, {v[5]}], yaw: {v[6]} }},')
        o.append('];')
        o.append('')
    o.append('/// `sCameraTriggers[level]`.')
    o.append('pub fn level_triggers(level: i32) -> &\'static [Trigger] {')
    o.append('    match level {')
    for lv, folder, table in levels:
        if table.startswith('sCam'):
            o.append(f'        {lv} => &{table.upper()},')
    o.append('        _ => &[],')
    o.append('    }')
    o.append('}')
    o.append('')
    o.append('/// `GEO_CAMERA` of each area: (level, area, default CAMERA_MODE, areaCenX, areaCenY, areaCenZ).')
    o.append(f'pub static AREA_CAMERAS: [(i32, i32, i32, f64, f64, f64); {len(area_cams)}] = [')
    for lv, area, mode, x, y, z in area_cams:
        o.append(f'    ({lv}, {area}, {mode}, {x}.0, {y}.0, {z}.0),')
    o.append('];')
    o.append('')
    o.append('/// `sBBHLibraryParTrackPath`: (startOfPath, pos, distThresh, zoom).')
    o.append(f'pub static BBH_LIBRARY_PAR_TRACK: [(i32, [f64; 3], f64, f64); {len(par_rows)}] = [')
    for r in par_rows:
        o.append(f'    ({r[0]}, [{float(r[1])}, {float(r[2])}, {float(r[3])}], {float(r[4])}, {float(r[5])}),')
    o.append('];')
    o.append('')
    o.append(f'pub const FIXED_MODE_BASE_POSITION: [f64; 3] = [{float(fixed[1])}, {float(fixed[2])}, {float(fixed[3])}];')
    o.append('')
    o.append('/// `sDanceCutsceneIndexTable[course][starIndex]` (high nibble = even star, low nibble = odd star).')
    o.append(f'pub static DANCE_CUTSCENE_INDEX: [[u8; 4]; {len(dance)}] = [')
    for r in dance:
        o.append('    [' + ', '.join(f'0x{b:02X}' for b in r) + '],')
    o.append('];')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(o) + '\n')
    print(f'wrote {OUT}: {len(levels)} levels, {len(tables)} trigger tables, {len(events)} events, {len(area_cams)} area cameras')


if __name__ == '__main__':
    main()
