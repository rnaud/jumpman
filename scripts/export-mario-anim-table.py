#!/usr/bin/env python3
"""Extract the SM64 Mario animation headers (flags, startFrame, loopStart, loopEnd) from the
decomp's assets/anims/*.inc.c into native/sim/src/mario_anim_data.rs. The sim needs them for
`is_anim_at_end` / `is_anim_past_frame` / `set_mario_animation` (src/game/mario.c).

usage: export-mario-anim-table.py [decomp-root] [output.rs]"""
import re
import sys
import pathlib

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else 'reference/sm64')
out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else 'native/sim/src/mario_anim_data.rs')
flag_names = {'ANIM_FLAG_NOLOOP': 1, 'ANIM_FLAG_BACKWARD': 2, 'ANIM_FLAG_2': 4, 'ANIM_FLAG_HOR_TRANS': 8,
              'ANIM_FLAG_VERT_TRANS': 16, 'ANIM_FLAG_5': 32, 'ANIM_FLAG_6': 64, 'ANIM_FLAG_7': 128}


def num(token):
    token = token.strip()
    if token in flag_names:
        return flag_names[token]
    if '|' in token:
        return sum(num(t) for t in token.split('|'))
    return int(token, 0)


rows = {}
pattern = re.compile(r'const struct Animation anim_([0-9A-F]+)\[\]\s*=\s*\{(.*?)\};', re.S)
for path in sorted((root / 'assets/anims').glob('*.inc.c')):
    for m in pattern.finditer(path.read_text()):
        fields = [f.strip() for f in m.group(2).split(',') if f.strip() and not f.strip().startswith('//')]
        flags, _div, start, loop_start, loop_end = (num(f) for f in fields[:5])
        rows[int(m.group(1), 16)] = (flags, start, loop_start, loop_end)

lines = ['//! Generated by scripts/export-mario-anim-table.py from the decomp `assets/anims/*.inc.c`.',
         '//! `(animation id, flags, startFrame, loopStart, loopEnd)` for every Mario animation.',
         '',
         'pub const MARIO_ANIM_HEADERS: &[(u16, u8, i16, i16, i16)] = &[']
for i in sorted(rows):
    f, s, ls, le = rows[i]
    lines.append(f'    (0x{i:02x}, {f}, {s}, {ls}, {le}),')
lines.append('];')
out.write_text('\n'.join(lines) + '\n')
print(len(rows), 'animations ->', out)
