import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--window-size=1440,900'],defaultViewport:{width:1440,height:900}});
const page = await browser.newPage();
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/?level=playground&character=procedural',{waitUntil:'networkidle0'});
await new Promise(r=>setTimeout(r,800)); await page.click('#start-button'); await new Promise(r=>setTimeout(r,400));
const state=()=>page.evaluate(()=>window.__JUMPMAN__.debugState);
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function waitFor(fn,timeout=3000){const t=Date.now();while(Date.now()-t<timeout){const s=await state();if(fn(s))return s;await sleep(12);}return await state();}
await page.keyboard.down('w'); await sleep(1200);
await page.keyboard.down('Space'); await sleep(45); await page.keyboard.up('Space');
let s=await waitFor(s=>['JUMP LAND','JUMP LAND STOP'].includes(s.actionName),2500);
console.log('land1',s.actionName,s.forwardVel.toFixed(1));
await page.keyboard.down('Space'); await sleep(45);
s=await waitFor(s=>s.actionName==='DOUBLE JUMP',1200); console.log('jump2',s.actionName);
await page.keyboard.up('Space');
s=await waitFor(s=>['DOUBLE JUMP LAND','DOUBLE JUMP LAND STOP'].includes(s.actionName),2500);
console.log('land2',s.actionName,s.forwardVel.toFixed(1));
await page.keyboard.down('Space'); await sleep(45);
s=await waitFor(s=>s.actionName==='TRIPLE JUMP',1200); console.log('jump3',s.actionName,s.forwardVel.toFixed(1));
await sleep(220);
await page.screenshot({path:'screenshots/06-triple-jump.png'});
await page.keyboard.up('Space'); await page.keyboard.up('w');
console.log('errors',errors);
await browser.close();
